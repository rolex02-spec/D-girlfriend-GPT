'use client';

import { useState, useEffect } from 'react';
import { motion } from 'framer-motion';

interface CharacterAvatarFallbackProps {
  character: {
    name: string;
    voice?: any;
    appearance: {
      skinColor?: string;
      eyeColor?: string;
      hairColor?: string;
    };
    nsfwAllowed?: boolean;
  };
  className?: string;
  size?: number;
  isActive?: boolean;
  isSpeaking?: boolean;
}

export default function CharacterAvatarFallback({ 
  character, 
  className = '',
  size = 64,
  isActive = false,
  isSpeaking = false
}: CharacterAvatarFallbackProps) {
  const [mounted, setMounted] = useState(false);

  // NOTE: this component draws a letter avatar — it never touches WebGL.
  // An earlier version probed `canvas.getContext('webgl')` per instance,
  // which exhausted Chrome's 16-context budget when 68 cards mounted at
  // once ("Too many active WebGL contexts"). The probe was unused dead
  // state and has been removed; only `mounted` remains for SSR parity.
  useEffect(() => {
    setMounted(true);
  }, []);
  
  return (
    <motion.div 
      // Size via INLINE STYLES: dynamic Tailwind classes like `h-${size}`
      // are never generated by the scanner, which made the fallback render
      // at the wrong size and pushed the letter outside its crop.
      className={`${className} flex items-center justify-center rounded-full bg-ink-2 border-2 ${isActive ? 'border-amber' : 'border-hairline'} ${isSpeaking ? 'animate-ring-pulse' : ''}`}
      style={{
        width: size,
        height: size,
        boxShadow: isActive 
          ? '0 0 20px rgba(217, 160, 90, 0.4)' 
          : '0 2px 8px rgba(0, 0, 0, 0.2)',
        transformStyle: 'preserve-3d',
      }}
      animate={isSpeaking ? { scale: [1, 1.02, 1] } : {}}
      transition={{ duration: 0.8, repeat: Infinity }}
    >
      <span style={{ fontSize: Math.round(size * 0.4), fontWeight: 700 }} className="text-paper-1">
        {character.name[0]}
      </span>
      {/* Subtle eye glow when active */}
      {isActive && (
        <div className="absolute inset-0 flex items-center justify-center pointer-events-none" style={{ opacity: 0.08 }}>
          <div className="flex gap-1" style={{ transform: 'translateY(-15%)' }}>
            <div className="rounded-full" style={{ width: size * 0.1, height: size * 0.1, background: character.appearance.eyeColor || '#4A2810', boxShadow: `0 0 ${size * 0.08}px ${character.appearance.eyeColor || '#4A2810'}` }} />
            <div className="rounded-full" style={{ width: size * 0.1, height: size * 0.1, background: character.appearance.eyeColor || '#4A2810', boxShadow: `0 0 ${size * 0.08}px ${character.appearance.eyeColor || '#4A2810'}` }} />
          </div>
        </div>
      )}
    </motion.div>
  );
}